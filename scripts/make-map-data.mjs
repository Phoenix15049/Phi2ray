// Generates src/mapData.ts: the dotted world map and rough coordinates per country and time zone.
// Usage: node scripts/make-map-data.mjs <world-atlas folder> <moment-timezone folder>
// Sources: Natural Earth land (public domain) via world-atlas, and the tz database via
// moment-timezone. Run it only to refresh the data; the app just imports the result.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [atlas, moment] = process.argv.slice(2);
const topo = JSON.parse(readFileSync(join(atlas, "land-110m.json"), "utf8"));
const [sx, sy] = topo.transform.scale;
const [tx, ty] = topo.transform.translate;
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => [(x += dx) * sx + tx, (y += dy) * sy + ty]);
});
const ring = (ids) =>
  ids.flatMap((id, i) => {
    const line = id < 0 ? [...arcs[~id]].reverse() : arcs[id];
    return i ? line.slice(1) : line;
  });
const rings = [];
for (const geometry of topo.objects.land.geometries) {
  const polygons = geometry.type === "Polygon" ? [geometry.arcs] : geometry.arcs;
  for (const polygon of polygons) for (const r of polygon) rings.push(ring(r));
}
const inside = (lon, lat) => {
  let odd = false;
  for (const r of rings) {
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
      const [xi, yi] = r[i];
      const [xj, yj] = r[j];
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) odd = !odd;
    }
  }
  return odd;
};

// One horizontal run per stretch of land; a dashed stroke turns the runs into dots.
const STEP = 2.5;
const TOP = 84;
const BOTTOM = -56;
let land = "";
for (let lat = TOP - STEP / 2; lat > BOTTOM; lat -= STEP) {
  let start = null;
  for (let lon = -180 + STEP / 2; lon <= 180; lon += STEP) {
    const on = lon < 180 && inside(lon, lat);
    if (on && start === null) start = lon;
    if (!on && start !== null) {
      land += `M${start + 180} ${+(TOP - lat).toFixed(2)}h${lon - STEP - start + 0.01}`;
      start = null;
    }
  }
}

const meta = JSON.parse(readFileSync(join(moment, "data/meta/latest.json"), "utf8"));
const packed = JSON.parse(readFileSync(join(moment, "data/packed/latest.json"), "utf8"));
const round = (v) => Math.round(v * 10) / 10;
const zones = {};
for (const [name, z] of Object.entries(meta.zones)) zones[name] = [round(z.lat), round(z.long)];
for (const link of packed.links) {
  const [target, alias] = link.split("|");
  if (zones[target] && !zones[alias]) zones[alias] = zones[target];
}
const countries = {};
for (const [code, c] of Object.entries(meta.countries)) if (zones[c.zones[0]]) countries[code] = zones[c.zones[0]];

writeFileSync(
  "src/mapData.ts",
  `// Generated by scripts/make-map-data.mjs. Natural Earth land (public domain), tz database coordinates.\n` +
    `export const MAP_TOP = ${TOP};\nexport const MAP_HEIGHT = ${TOP - BOTTOM};\nexport const MAP_STEP = ${STEP};\n` +
    `export const LAND = ${JSON.stringify(land)};\n` +
    `export const ZONES: Record<string, [number, number]> = ${JSON.stringify(zones)};\n` +
    `export const COUNTRIES: Record<string, [number, number]> = ${JSON.stringify(countries)};\n`,
);
console.log("land", land.length, "zones", Object.keys(zones).length, "countries", Object.keys(countries).length);
